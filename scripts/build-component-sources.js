/**
 * Builds assets/ui/component-sources.js: the real package source files behind
 * each component page's "Component Source" panel in index.html.
 *
 * That panel used to read hand-written listings embedded in index.html, which
 * claimed paths like composeApp/.../SnackyModal.kt and src/components/Modal.tsx
 * that do not exist. They drifted from the packages the same way the old
 * hand-written Live Preview did; the Modal listing even defined its own
 * BottomSheet and a SnackyModal/ModalType API that neither package exports.
 * Now the panel shows the files that actually ship, read from packages/ at
 * build time, under their real paths.
 *
 * The output is a script (not JSON) so it also loads when index.html is opened
 * from disk, and index.html injects it only when a panel is first opened.
 *
 * Runs as part of `node scripts/build-docs-bundle.js`, or on its own:
 *   node scripts/build-component-sources.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const KT_DIR = 'packages/compose-ui/src/commonMain/kotlin/com/snacky/ui/components';
const RX_DIR = 'packages/react-ui/src/components';
const OUT = path.join(ROOT, 'assets', 'ui', 'component-sources.js');

// index.html component page id -> [compose-ui folder, react-ui folder].
// Pages not listed keep their own index.html block: `icon` shows a reference
// generated from assets/icons/icons.json by scripts/generate-icons.js.
const PAGES = {
  button: ['button', 'Button'],
  'icon-button': ['iconbutton', 'IconButton'],
  input: ['input', 'Input'],
  calendar: ['calendar', 'Calendar'],
  chips: ['chips', 'Chips'],
  'radio-button': ['radiobutton', 'RadioButton'],
  checkbox: ['checkbox', 'Checkbox'],
  toggle: ['toggle', 'Toggle'],
  navbar: ['navbar', 'Navbar'],
  tab: ['tab', 'Tab'],
  header: ['header', 'Header'],
  banner: ['banner', 'Banner'],
  badge: ['badge', 'Badge'],
  stepper: ['stepper', 'Stepper'],
  callout: ['callout', 'Callout'],
  list: ['list', 'List'],
  accordion: ['accordion', 'Accordion'],
  modal: ['modal', 'Modal'],
  section: ['section', 'Section'],
  avatar: ['avatar', 'Avatar'],
  illustration: ['illustration', 'Illustration'],
  'product-image': ['productimage', 'ProductImage'],
  'product-card': ['productcard', 'ProductCard'],
};
// Package folders with no docs page of their own.
const UNPAGED = new Set(['icon', 'imageplaceholder', 'Icon', 'ImagePlaceholder']);

// Components first, then their stylesheet, then the barrel export.
const rank = (f) => (/\.(kt|tsx)$/.test(f) ? 0 : f.endsWith('.css') ? 1 : 2);

function readFolder(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) throw new Error(`missing package folder: ${dir}`);
  return fs
    .readdirSync(abs)
    .filter((f) => fs.statSync(path.join(abs, f)).isFile())
    .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
    .map((f) => ({
      path: `${dir}/${f}`,
      code: fs.readFileSync(path.join(abs, f), 'utf8').replace(/\r\n/g, '\n').trimEnd(),
    }));
}

function buildComponentSources() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  for (const id of Object.keys(PAGES)) {
    if (!html.includes(`'${id}':{`) && !html.includes(`\n  ${id}:{`)) {
      throw new Error(`index.html has no component page "${id}"`);
    }
  }
  for (const [dir, side] of [[KT_DIR, 0], [RX_DIR, 1]]) {
    const mapped = new Set(Object.values(PAGES).map((p) => p[side]));
    const orphans = fs
      .readdirSync(path.join(ROOT, dir))
      .filter((d) => !mapped.has(d) && !UNPAGED.has(d) && fs.statSync(path.join(ROOT, dir, d)).isDirectory());
    if (orphans.length) throw new Error(`${dir}: not mapped to a docs page: ${orphans.join(', ')}`);
  }

  const sources = {};
  for (const [id, [kt, rx]] of Object.entries(PAGES)) {
    sources[id] = { kotlin: readFolder(`${KT_DIR}/${kt}`), react: readFolder(`${RX_DIR}/${rx}`) };
  }

  const banner =
    '/*! Snacky UI component sources, generated by scripts/build-component-sources.js\n' +
    ' * from packages/compose-ui and packages/react-ui, do not hand-edit. */\n';
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, banner + 'window.SNACKY_SOURCES=' + JSON.stringify(sources) + ';\n');

  const files = Object.values(sources).reduce((n, s) => n + s.kotlin.length + s.react.length, 0);
  const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
  console.log(`Wrote assets/ui/component-sources.js: ${Object.keys(sources).length} pages, ${files} files, ${kb} KB`);
}

module.exports = { buildComponentSources };
if (require.main === module) buildComponentSources();
